    private InteresesDAO interesDAO;
    private ArrayList<Intereses> listadoIntereses;
    
    public frmGraficoDeBarra() {
        initComponents();
        
        interesDAO = new InteresesDAO();
        listadoIntereses = interesDAO.consultarCantidadInteresados();
        
        cargarGrafico(); 
    }
    
    private DefaultCategoryDataset obtenerDatos(){
        DefaultCategoryDataset datos = new DefaultCategoryDataset();
        
        for(int i = 0; i < listadoIntereses.size(); i++){
            datos.setValue(listadoIntereses.get(i).getCantidad(), "", listadoIntereses.get(i).getNombreCarrera());
        }
        
        return datos;
    }
    
    private void cargarGrafico(){
        DefaultCategoryDataset datos = obtenerDatos();
        
        JFreeChart graficoDeBarra = ChartFactory.createBarChart3D(
                "Cantidad de Interesados por Carrera",  //Nombre del gráfico
                "Cantidad de Estudiantes Interesados",  //Nombre de las barras o columnas
                "Carreras",                             //Nombre de la numeración
                datos,                                  //Datos del gráfico
                PlotOrientation.VERTICAL,               //Orientación del gráfico
                true,                                   //Leyenda de barrar individuales
                true,                                   //Herramientas
                false                                   //URL del gráfico
        );
        
        ChartPanel panel = new ChartPanel(graficoDeBarra);
        panel.setMouseWheelEnabled(true);
        panel.setPreferredSize(new Dimension(938, 608));
        
        this.jpGrafico.setLayout(new BorderLayout());
        this.jpGrafico.add(panel, BorderLayout.NORTH);
        
        pack();
        repaint(); //Estas lineas de código es para asegurarse de que el gráfico no se borre.
    }


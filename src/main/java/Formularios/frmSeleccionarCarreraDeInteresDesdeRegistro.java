    private void jtCarrerasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtCarrerasMouseClicked
        // TODO add your handling code here:
        int filaSeleccionada = this.jtCarreras.getSelectedRow();

        int IDCarrera = Integer.parseInt(String.valueOf(this.jtCarreras.getValueAt(filaSeleccionada, 0)));
        String carrera = String.valueOf(this.jtCarreras.getValueAt(filaSeleccionada, 1));
        String descripcion = String.valueOf(this.jtCarreras.getValueAt(filaSeleccionada, 2));

        carreraSeleccionada = new Carrera(
            IDCarrera,
            carrera,
            descripcion
        );
        
        if(frmPadre.comprobarCarrera(carreraSeleccionada)){
            frmPadre.añadirCarreraDeInteres(carreraSeleccionada);
            this.setVisible(false);
            this.dispose();
        }
        else{            
            JOptionPane.showMessageDialog(null, "Esta carrera ya esta en sus intereses", "¡¡ERROR!!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jtCarrerasMouseClicked


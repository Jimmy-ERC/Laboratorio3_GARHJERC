    private void mostrarDatosDelUsuario(){        
        this.txtNombre.setText(usuario.getNombre());
        this.txtApellido.setText(usuario.getApellido());
        this.txtEdad.setText(String.valueOf(usuario.getEdad()));
        this.cbRegion.setSelectedItem(usuario.getRegion());
        this.txtUsuario.setText(usuario.getUsuario());
    }
    
    private boolean validarCamposVacios() {
        if (this.txtNombre.getText().isEmpty() || this.txtNombre.getText().isBlank()) {
            return false;
        }

        if (this.txtApellido.getText().isEmpty() || this.txtApellido.getText().isBlank()) {
            return false;
        }

        if (this.txtEdad.getText().isEmpty() || this.txtEdad.getText().isBlank()) {
            return false;
        }

        if (this.cbRegion.getSelectedIndex() < 0) {
            return false;
        }

        if (this.txtUsuario.getText().isEmpty() || this.txtUsuario.getText().isBlank()) {
            return false;
        }

        return true;
    }


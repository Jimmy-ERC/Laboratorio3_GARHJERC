    private void btnEliminarCarreraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarCarreraActionPerformed
        // TODO add your handling code here:
        if(carreraSeleccionada != null){            
            int opcionSeleccionada = JOptionPane.showConfirmDialog(null, "¿Desea eliminar la carrera" + carreraSeleccionada.getNombreCarrera() + " de sus intereses?", "¡Desea eliminar el usuario?", JOptionPane.YES_NO_OPTION);
            
            if (opcionSeleccionada == 0) {
                eliminarCarreraDeInteres(this.jtCarreras.getSelectedRow());
                cargarCarrerasDeInteres();
            }
        }
        else{
            JOptionPane.showMessageDialog(null, "Seleccione la carrera que quiere eliminar de sus intereses", "¡¡ERROR!!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarCarreraActionPerformed

    private void btnRegistraseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistraseActionPerformed
        // TODO add your handling code here:
        if(validarCamposVacios() && validarEmail()){
            if(!listadoCarrerasDeInteres.isEmpty()){
                Usuario usuarioNuevo = new Usuario(
                        this.txtNombre.getText(),
                        this.txtApellido.getText(),
                        this.txtEmail.getText(),
                        Integer.parseInt(this.txtEdad.getText()),
                        this.txtRegion.getText(),
                        "Estudiante",
                        this.txtUsuario.getText(),
                        this.txtContraseña.getText()
                );
                
                usuarioDAO.insertarUsuario(usuarioNuevo);
                
                int IDUsuarioNuevo = usuarioDAO.obtenerUltimoIDUsuario();
                
                for(int i = 0; i < listadoCarrerasDeInteres.size(); i++){
                    Interes intereses = new Interes(                    
                            IDUsuarioNuevo,
                            listadoCarrerasDeInteres.get(i).getIDCarrera()
                    );
                    
                    interesesDAO.insertarInteres(intereses);
                }
                
                frmLogin login = new frmLogin();
                login.setVisible(true);
                this.dispose();
            }
            else{          
                JOptionPane.showMessageDialog(null, "Al menos debe agregar una carrera de interes", "¡¡ERROR!!", JOptionPane.ERROR_MESSAGE);
            }                
        }
        else{
            JOptionPane.showMessageDialog(null, "Ingrese los datos correctamente", "¡¡ERROR!!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRegistraseActionPerformed


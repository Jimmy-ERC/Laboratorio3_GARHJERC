    private void cargarCarrerasDeInteres() {
        this.modeloCarreras.setRowCount(0);

        for (int i = 0; i < this.listadoCarrerasDeInteres.size(); i++) {
            Carrera carrera = this.listadoCarrerasDeInteres.get(i);

            String[] data = {
                String.valueOf(carrera.getIDCarrera()),
                carrera.getNombreCarrera(),
                carrera.getDescripcion()
            };

            this.modeloCarreras.addRow(data);
        }

        this.jtCarreras.setModel(modeloCarreras);
    }
    
    public void añadirCarreraDeInteres(Carrera carrera){
        listadoCarrerasDeInteres.add(carrera);
        
        cargarCarrerasDeInteres();
    }
    
    private void eliminarCarreraDeInteres(int removerElemento){
        listadoCarrerasDeInteres.remove(removerElemento);
    }
    
    public boolean comprobarCarrera(Carrera carrera) {
        for (Carrera c : listadoCarrerasDeInteres) {
            if (c.getNombreCarrera().equals(carrera.getNombreCarrera())) {
                return false;
            }
        }
        return true;
    }
    
    private boolean validarCamposVacios() {
        if (this.txtNombre.getText().isEmpty() || this.txtNombre.getText().isBlank()) {
            return false;
        }

        if (this.txtApellido.getText().isEmpty() || this.txtApellido.getText().isBlank()) {
            return false;
        }

        if (this.txtEmail.getText().isEmpty() || this.txtEmail.getText().isBlank()) {
            return false;
        }

        if (this.txtEdad.getText().isEmpty() || this.txtEdad.getText().isBlank()) {
            return false;
        }

        if (this.txtRegion.getText().isEmpty() || this.txtRegion.getText().isBlank()) {
            return false;
        }

        if (this.txtUsuario.getText().isEmpty() || this.txtUsuario.getText().isBlank()) {
            return false;
        }

        if (this.txtContraseña.getText().isEmpty() || this.txtContraseña.getText().isBlank()) {
            return false;
        }

        return true;
    }
    
    private boolean validarEmail(){
        if(this.txtEmail.getText().endsWith("@gmail.com")){
            return true;
        }       
        
        if(this.txtEmail.getText().endsWith("@yahoo.com")){
            return true;
        }
        
        if(this.txtEmail.getText().endsWith("@hotmail.com")){
            return true;
        }
        
        return false;
    }


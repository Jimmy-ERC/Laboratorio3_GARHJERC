    private void btnActualizarContraseñaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarContraseñaActionPerformed
        // TODO add your handling code here:
        if (validarCamposVacios()) {
            if (validarContraseña()) {
                if (validarNuevaContraseña()) {
                    if (validarContraseñasRepetidasConLaAnterior()) {
                        Usuario usuario = new Usuario(
                                this.usuario.getIDUsuario(),
                                this.usuario.getNombre(),
                                this.usuario.getApellido(),
                                this.usuario.getEmail(),
                                this.usuario.getEdad(),
                                this.usuario.getRegion(),
                                this.usuario.getRol(),
                                this.usuario.getUsuario(),
                                this.txtNuevaContraseña.getText()
                        );

                        if (usuarioDAO.editarUsuario(usuario)) {
                            frmPadre.setUsuario(usuario);
                        }
                    }
                    else {
                        JOptionPane.showMessageDialog(null, "La contraseña no puede ser la misma que la anterior", "¡¡ERROR!!", JOptionPane.ERROR_MESSAGE);
                    }
                } 
                else {
                    JOptionPane.showMessageDialog(null, "La contraseña debe repetirse, ingrese los datos correctamente", "¡¡ERROR!!", JOptionPane.ERROR_MESSAGE);
                }
            } 
            else {
                JOptionPane.showMessageDialog(null, "Contraseña incorrecta", "¡¡ERROR!!", JOptionPane.ERROR_MESSAGE);
            }
        } 
        else {
            JOptionPane.showMessageDialog(null, "Ingrese los datos correctamente", "¡¡ERROR!!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarContraseñaActionPerformed



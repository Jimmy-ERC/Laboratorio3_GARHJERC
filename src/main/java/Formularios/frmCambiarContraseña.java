    private void mostrarContraseña() {
        if (this.chkVerContraseña.isSelected()) {
            this.txtContraseñaAnterior.setEchoChar((char) 0);
            this.txtNuevaContraseña.setEchoChar((char) 0);
            this.txtContraseñaRepitidaNueva.setEchoChar((char) 0);
        } else {
            this.txtContraseñaAnterior.setEchoChar('*');
            this.txtNuevaContraseña.setEchoChar('*');
            this.txtContraseñaRepitidaNueva.setEchoChar('*');
        }
    }

    private boolean validarCamposVacios() {
        if (this.txtNuevaContraseña.getText().isEmpty() || this.txtNuevaContraseña.getText().isBlank()) {
            return false;
        }

        if (this.txtContraseñaRepitidaNueva.getText().isEmpty() || this.txtContraseñaRepitidaNueva.getText().isBlank()) {
            return false;
        }

        if (this.txtContraseñaAnterior.getText().isEmpty() || this.txtContraseñaAnterior.getText().isBlank()) {
            return false;
        }

        return true;
    }

    private boolean validarContraseña() {
        if (!this.txtContraseñaAnterior.getText().equals(usuario.getContraseña())) {
            return false;
        }

        return true;
    }

    private boolean validarNuevaContraseña() {
        if (!this.txtNuevaContraseña.getText().equals(this.txtContraseñaRepitidaNueva.getText())) {
            return false;
        }

        return true;
    }

    private boolean validarContraseñasRepetidasConLaAnterior() {
        if (this.txtContraseñaAnterior.getText().equals(this.txtNuevaContraseña.getText())) {
            return false;
        }

        return true;
    }


    private void jtUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtUsuariosMouseClicked
        // TODO add your handling code here:
        int filaSeleccionada = this.jtUsuarios.getSelectedRow();

        int IDUsuario = Integer.parseInt(String.valueOf(this.jtUsuarios.getValueAt(filaSeleccionada, 0)));
        String nombre = String.valueOf(this.jtUsuarios.getValueAt(filaSeleccionada, 1));
        String apellido = String.valueOf(this.jtUsuarios.getValueAt(filaSeleccionada, 2));
        String email = String.valueOf(this.jtUsuarios.getValueAt(filaSeleccionada, 3));
        int edad = Integer.parseInt(String.valueOf(this.jtUsuarios.getValueAt(filaSeleccionada, 4)));
        String region = String.valueOf(this.jtUsuarios.getValueAt(filaSeleccionada, 5));
        String rol = String.valueOf(this.jtUsuarios.getValueAt(filaSeleccionada, 6));
        String usuario = String.valueOf(this.jtUsuarios.getValueAt(filaSeleccionada, 7));
        String contraseña = String.valueOf(this.jtUsuarios.getValueAt(filaSeleccionada, 8));

        usuarioSeleccionado = new Usuario(
                IDUsuario,
                nombre,
                apellido,
                email,
                edad,
                region,
                rol,
                usuario,
                contraseña
        );

        this.txtNombre.setText(nombre);
        this.txtApellido.setText(apellido);
        this.txtEmail.setText(email);
        this.txtEdad.setText(String.valueOf(edad));
        this.txtRegion.setText(region);
        this.cbRol.setSelectedItem(rol);
        this.txtUsuario.setText(usuario);
        this.txtContraseña.setText(contraseña);
    }//GEN-LAST:event_jtUsuariosMouseClicked


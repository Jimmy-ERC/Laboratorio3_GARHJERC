    private void cargarUsuarios() {
        listadoUsuarios = usuarioDAO.consultarUsuarios();
        this.modeloUsuarios.setRowCount(0);

        for (int i = 0; i < this.listadoUsuarios.size(); i++) {
            Usuario usuario = this.listadoUsuarios.get(i);

            String[] data = {
                String.valueOf(usuario.getIDUsuario()),
                usuario.getNombre(),
                usuario.getApellido(),
                usuario.getEmail(),
                String.valueOf(usuario.getEdad()),
                usuario.getRegion(),
                usuario.getRol(),
                usuario.getUsuario(),
                usuario.getContraseña()
            };

            this.modeloUsuarios.addRow(data);
        }

        this.jtUsuarios.setModel(modeloUsuarios);
    }

    private void buscarUsuarios(String nombreUsuario) {
        listadoUsuarios = usuarioDAO.buscarUsuarios(nombreUsuario);
        this.modeloUsuarios.setRowCount(0);

        for (int i = 0; i < this.listadoUsuarios.size(); i++) {
            Usuario usuario = this.listadoUsuarios.get(i);

            String[] data = {
                String.valueOf(usuario.getIDUsuario()),
                usuario.getNombre(),
                usuario.getApellido(),
                usuario.getEmail(),
                String.valueOf(usuario.getEdad()),
                usuario.getRegion(),
                usuario.getRol(),
                usuario.getUsuario(),
                usuario.getContraseña()
            };

            this.modeloUsuarios.addRow(data);
        }

        this.jtUsuarios.setModel(modeloUsuarios);
    }

    private boolean validarCamposVacios() {
        if (this.txtNombre.getText().isEmpty() || this.txtNombre.getText().isBlank()) {
            return false;
        }

        if (this.txtApellido.getText().isEmpty() || this.txtApellido.getText().isBlank()) {
            return false;
        }

        if (this.txtEmail.getText().isEmpty() || this.txtEmail.getText().isBlank()) {
            return false;
        }

        if (this.txtEdad.getText().isEmpty() || this.txtEdad.getText().isBlank()) {
            return false;
        }

        if (this.txtRegion.getText().isEmpty() || this.txtRegion.getText().isBlank()) {
            return false;
        }

        if (this.cbRol.getSelectedIndex() < 0) {
            return false;
        }

        if (this.txtUsuario.getText().isEmpty() || this.txtUsuario.getText().isBlank()) {
            return false;
        }

        if (this.txtContraseña.getText().isEmpty() || this.txtContraseña.getText().isBlank()) {
            return false;
        }

        return true;
    }

    private boolean validarNombreSinNumeros() {
        try {
            Integer.parseInt(this.txtNombre.getText());
            return false;
        } 
        catch (Exception e) {
            return true;
        }
    }

    private boolean validarApellidoSinNumeros() {
        try {
            Integer.parseInt(this.txtApellido.getText());
            return false;
        } 
        catch (Exception e) {
            return true;
        }
    }


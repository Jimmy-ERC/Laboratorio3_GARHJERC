    private InteresDAO interesDAO;
    private ArrayList<Interes> listadoIntereses;
    
    public frmGraficoDePastel() {
        initComponents();
        
        interesDAO = new InteresDAO();
        listadoIntereses = interesDAO.consultarCantidadInteresados();
        
        cargarGrafico();        
    }
    
    private DefaultPieDataset obtenerDatos(){
        DefaultPieDataset datos = new DefaultPieDataset();
        
        for(int i = 0; i < listadoIntereses.size(); i++){
            datos.setValue(listadoIntereses.get(i).getNombreCarrera(), listadoIntereses.get(i).getCantidad());
        }
        
        return datos;
    }
    
    private void cargarGrafico(){
        DefaultPieDataset datos = obtenerDatos();
        
        JFreeChart graficoCircular = ChartFactory.createPieChart(
                "Cantidad de interesados por carrera",    //Nombre del gráfico
                datos,                                      //Datos del gráfico
                true,                                       //Nombre de las categorias
                true,                                       //Herramientas
                false                                       //URL del gráfico
        );
        
        ChartPanel panel = new ChartPanel(graficoCircular);
        panel.setMouseWheelEnabled(true);
        panel.setPreferredSize(new Dimension(938, 608));
        
        this.jpGrafico.setLayout(new BorderLayout());
        this.jpGrafico.add(panel, BorderLayout.NORTH);
        
        pack();
        repaint(); //Estas lineas de código es para asegurarse de que el gráfico no se borre.
    }


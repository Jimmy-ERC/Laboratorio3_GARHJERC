    private void cargarCarreras() {
        listadoCarreras = carreraDAO.consultarCarreras();
        this.modeloCarreras.setRowCount(0);

        for (int i = 0; i < this.listadoCarreras.size(); i++) {
            Carrera carrera = this.listadoCarreras.get(i);

            String[] data = {
                String.valueOf(carrera.getIDCarrera()),
                carrera.getNombreCarrera(),
                carrera.getDescripcion()
            };

            this.modeloCarreras.addRow(data);
        }

        this.jtCarreras.setModel(modeloCarreras);
    }

    private void buscarCarreras(String nombreCarrera) {
        listadoCarreras = carreraDAO.buscarCarreras(nombreCarrera);
        this.modeloCarreras.setRowCount(0);

        for (int i = 0; i < this.listadoCarreras.size(); i++) {
            Carrera usuario = this.listadoCarreras.get(i);

            String[] data = {
                String.valueOf(usuario.getIDCarrera()),
                usuario.getNombreCarrera(),
                usuario.getDescripcion()
            };

            this.modeloCarreras.addRow(data);
        }

        this.jtCarreras.setModel(modeloCarreras);
    }

